def _render_style_notes() -> str:
    return (
        "写法要点：\n"
        "- plan_text 像研究开始前的行动计划，说明“先怎么整理、再怎么判断、最后产出什么”。\n"
        "- plan_steps 是给系统保留的动作清单，把 plan_text 里的动作拆成 3-5 个可检查步骤。\n"
        "- plan_text 不要塞满章节名和知识点；具体知识内容放到 chapters。\n"
        "- chapters 可以更具体，每章标题清楚，key_points 落到知识点、题型、方法或易错边界。"
    )


def _render_chapters(chapters: list[dict[str, Any]]) -> str:
    lines = []
    for chapter in chapters:
        key_points = "；".join(chapter.get("key_points") or [])
        lines.append(f"  - {chapter.get('title', '')}：{key_points}")
    return "\n".join(lines)


def _render_plan_steps(items: list[str]) -> str:
    return "\n".join(f"  - {item}" for item in items)


def render_plan_sketch_examples() -> str:
    blocks = []
    for index, item in enumerate(PLAN_SKETCH_EXAMPLES, start=1):
        blocks.append(f"示例 {index}\n输入：{item['input']}\n输出：\n{item['output']}")
    return "\n\n".join(blocks)


def render_plan_intent_examples() -> str:
    blocks = []
    for index, item in enumerate(PLAN_INTENT_EXAMPLES, start=1):
        output = item["output"]
        blocks.append(
            f"示例 {index}\n"
            f"输入：{item['input']}\n"
            f"输出 plan_intent：{output['plan_intent']}\n"
            f"输出 plan_queries：\n{_render_query_list(output['plan_queries'])}"
        )
    return "\n\n".join(blocks)


def render_composer_examples() -> str:
    blocks = [_render_style_notes()]
    for index, item in enumerate(COMPOSER_EXAMPLES, start=1):
        output = item["output"]
        blocks.append(
            f"示例 {index}\n"
            f"输入：{item['input']}\n"
            f"输出 plan_text：{output['plan_text']}\n"
            f"输出 plan_steps：\n{_render_plan_steps(output.get('plan_steps') or [])}\n"
            f"输出 chapters：\n{_render_chapters(output['chapters'])}"
        )
    return "\n\n".join(blocks)


def _render_query_list(items: list[str]) -> str:
    return "\n".join(f"  - {item}" for item in items)


