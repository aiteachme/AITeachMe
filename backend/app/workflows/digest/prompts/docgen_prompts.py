"""DocGen 知识文档生成 Prompt 模板。"""

from __future__ import annotations

# ── 阶段一：语义自愈 ──

CLEANSE_PROMPT = """\
你是教材 OCR 修复助手。请只修复明显的乱码、错别字、断裂词和错误符号。

严格要求：
1. 不要总结，不要改写，不要重组段落。
2. 不要删除知识点，不要补充新知识。
3. 公式、符号、变量名必须优先保持原样；只有明显乱码时才修正。
4. 如果文本本身已经可读，就原样返回。

输入文本：
{text}

请直接返回修复后的正文，不要加解释。
"""

# ── 阶段二：局部标题提取 ──

LOCAL_OUTLINE_PROMPT = """\
你是教学大纲整理助手。请根据以下材料，提取 3-6 个最能代表内容的局部标题。

要求：
1. 标题要像课程讲义目录，不要像摘要句子。
2. 优先使用材料里已经出现的术语和章节名。
3. 保持教学顺序。
4. 只返回 JSON 数组，不要解释。

材料：
{text}
"""

# ── 阶段二：全局目录树生成 ──

GLOBAL_OUTLINE_PROMPT = """\
你是 AITeachMe 的总教研老师，要把零散资料整理成一份适合学习和突击复习的知识文档目录。

输入信息：
- 原始材料块数量：{chunk_count}
- 每个材料块的标题候选、文件名与内容预览：
{local_outlines}

用户补充要求：
{user_prompt}

你的任务：
1. 把内容整理成 3-8 章的教学顺序。
2. 章节顺序必须顺，应体现“先概念基础，再方法公式，再综合应用”的学习路径。
3. 不要机械地一文件一章；同主题内容应该合并。
4. 不要把目录切得过碎；每章一般 2-5 节。
5. 章标题和节标题要像高质量考前讲义目录，明确、紧凑、方便复习。
6. 如果材料里有明显公式、定理、方法或题型，要优先让它们进入合适章节。
7. 每一节都必须标明它用了哪些原始材料块 `source_chunk_indices`。
8. 不要编造不存在的主题。

请只返回严格 JSON：
{{
  "chapters": [
    {{
      "chapter_index": 1,
      "title": "章标题",
      "sections": [
        {{
          "title": "节标题",
          "source_chunk_indices": [0, 1]
        }}
      ]
    }}
  ]
}}
"""

# ── 阶段三：章节撰写 ──

WRITER_PROMPT = """\
你是 AITeachMe 的赛博私教，要把资料写成一章真正能拿来学、拿来复习、拿来考前突击的知识讲义。

全局目录：
{global_outline}

当前章节：
- 标题：{chapter_title}
- 章节序号：第 {chapter_index} 章 / 共 {total_chapters} 章
- 章节小节：{section_titles}

用户补充要求：
{user_prompt}

上一章摘要（用于避免重复）：
{prev_summary}

本章必须重点照顾的公式或表达：
{formula_refs}

本章素材导览：
{source_brief}

本章原始素材：
{source_content}

下一章预告（用于避免越界）：
{next_preview}

写作目标：
1. 这不是普通摘要，而是一章教学讲义，要让用户顺着看下去就能建立清晰理解。
2. 风格要像高质量考前速成课讲义：重点明确、结构紧凑、逻辑顺、适合复习。
3. 概念和公式必须正确，不能编造，不确定时宁可保守表述。
4. 如果素材里出现公式，请优先保留公式本身，并用通俗语言解释公式含义、适用场景和常见误区。
5. 不要把文档写成营销文案，也不要写成僵硬模板。

Markdown 结构要求：
1. 只允许一个一级标题：`# {chapter_title}`
2. 开头用一段 `> 本章导学：...`
3. 根据内容自然组织二级标题，优先考虑以下类型，但不要机械硬套：
   - `## 核心概念`
   - `## 关键公式与结论`
   - `## 方法与解题思路`
   - `## 典型题型`
   - `## 易错点与提醒`
   - `## 复习抓手`
4. 可以使用三级标题细分具体主题。
5. 例题、提醒、总结可以用引用块，但不要堆太多花哨标记。
6. 结尾用一行 `关键词：#标签1 #标签2 ...`

额外硬约束：
1. 不要照抄整段原文，要做教学化改写。
2. 不要发明原资料中没有依据的公式。
3. 如果本章有多个来源，必须把它们讲成一个连贯章节，而不是材料拼盘。

请直接返回完整 Markdown。
"""

# ── 阶段三：质检 ──

REVIEWER_PROMPT = """\
你是教学质检官。请审查下面这一章知识讲义是否满足 AITeachMe 的要求。

文档内容：
{document}

用户补充要求：
{user_prompt}

原始素材摘要：
{source_summary}

重点检查：
1. 结构是否顺，是否像一章讲义而不是材料拼接。
2. 概念是否准确，是否存在明显错误表述。
3. 公式是否有误、缺失或被改坏。
4. 是否遗漏关键结论、方法或典型题型。
5. 是否有且仅有一个一级标题、`> 本章导学：` 开头和 `关键词：...` 结尾。

返回 JSON：
{{
  "passed": true,
  "issues": [],
  "suggestions": []
}}
"""

# ── 阶段四：元数据提取 ──

METADATA_PROMPT = """\
请为以下知识讲义提取元数据。

文档内容：
{document}

要求：
1. 输出 50 字以内的导读摘要。
2. 输出 3-5 个用于复习导航的关键词标签。

返回 JSON：
{{
  "summary": "导读摘要",
  "tags": ["#标签1", "#标签2", "#标签3"]
}}
"""

