"""DocGen 知识文档生成 Prompt 模板。"""

from __future__ import annotations

# ── 阶段一：语义自愈 ──

CLEANSE_PROMPT = """\
你是一个文本修复专家。你的唯一任务是：修复以下文本中因 OCR 识别或 PDF 提取产生的错别字和乱码。

## 严格约束
- 仅修复明显的 OCR 错误（如"夫学"→"大学"、"圆数"→"函数"）
- 保持原文结构与逻辑绝对不变
- 不可进行任何总结、改写、重组或删减
- 不可添加任何新内容
- 如果文本没有明显错误，原样返回

## 输入文本
{text}

## 输出
直接返回修复后的文本，不要添加任何前缀说明。
"""

# ── 阶段二：局部标题提取 ──

LOCAL_OUTLINE_PROMPT = """\
你是一个教学大纲助理。请根据以下文本内容，提取或生成 3-5 个概括性子标题，用于描述该段文本涵盖的主要知识点。

## 约束
- 子标题应简洁精确，每个不超过 20 字
- 按内容出现顺序排列
- 只返回标题列表，不要解释

## 文本内容
{text}

## 输出格式
返回 JSON 数组，例如：
["标题一", "标题二", "标题三"]
"""

# ── 阶段二：全局目录树生成 ──

GLOBAL_OUTLINE_PROMPT = """\
你是一位经验丰富的教研主管。请将以下零散的知识点标题列表，按照从易到难的教学逻辑，重新编排为一棵结构化的目录树。

## 输入
- 原始文本块数量：{chunk_count}
- 各文本块的局部标题汇总：
{local_outlines}

## 要求
1. 组织为"章-节"的两级结构（chapter → section）
2. 每一章应有一个概括性的章标题
3. 同一主题的内容应归入同一章
4. 章节按照教学逻辑排序（基础概念在前，高级应用在后）
5. 对每一节，明确标注它对应使用了哪些原始文本块（用索引号 0, 1, 2...）

## 输出格式
返回严格的 JSON，结构如下：
{{
  "chapters": [
    {{
      "chapter_index": 1,
      "title": "章标题",
      "sections": [
        {{
          "title": "节标题",
          "source_chunk_indices": [0, 1]
        }}
      ]
    }}
  ]
}}
"""

# ── 阶段三：章节撰写 ──

WRITER_PROMPT = """\
你是 AITeachMe 的金牌私教。请基于分配的原始素材，撰写一篇结构化、可阅读的教学知识文档章节。

## 全局大纲
{global_outline}

## 当前章节信息
- 章节标题：{chapter_title}
- 章节序号：第 {chapter_index} 章（共 {total_chapters} 章）

## 上一节摘要（防重复）
{prev_summary}

## 本节分配的原始素材
{source_content}

## 下一节预告（防越界）
{next_preview}

## 写作规范
1. 以 `# {chapter_title}` 作为唯一一级标题
2. 用 `> 📌 本章概要：` 开头，2-3 句话概括本章核心内容
3. 用 `## 1. 知识点标题` 作为二级标题骨架
4. 用 `### 子话题` 作为三级标题
5. 核心概念用 `> 💡 **重点** ...` 标记
6. 例题用 `> 📝 **例题** ...` 标记
7. 易错点用 `> ⚠️ **易错点** ...` 标记
8. 关联知识用 `> 🔗 **关联** ...` 标记
9. 公式保留 LaTeX 格式（用 `$...$` 或 `$$...$$`）
10. 文档末尾附标签行：`📊 本章标签：#标签1 #标签2 ...`
11. 不可照搬原文，必须用通俗易懂的教学语言重写
12. 保留原始资料中的所有核心概念和公式，不可遗漏

## 输出
直接返回完整的 Markdown 文档，不要添加任何前缀说明。
"""

# ── 阶段三：质检 ──

REVIEWER_PROMPT = """\
你是一位严格的教学质检官。请检查以下知识文档是否符合 AITeachMe 的文档规范。

## 文档内容
{document}

## 检查项
1. 是否有且仅有一个一级标题（`#`）
2. 是否有 `> 📌 本章概要：` 开头段
3. 是否使用了 `> 💡 **重点**`、`> 📝 **例题**` 等标记
4. 公式是否使用了 LaTeX 格式
5. 是否有末尾标签行 `📊 本章标签：...`
6. 内容是否遗漏了原始素材中的核心概念

## 原始素材摘要
{source_summary}

## 输出格式
返回 JSON：
{{
  "passed": true/false,
  "issues": ["问题描述1", "问题描述2"],
  "suggestions": ["修改建议1"]
}}
"""

# ── 阶段四：元数据提取 ──

METADATA_PROMPT = """\
请为以下知识文档提取元数据。

## 文档内容
{document}

## 要求
1. 生成一段 50 字以内的导读摘要（summary）
2. 提取 3-5 个标签（tags），如 `#核心概念` `#公式推导` `#易考点` 等

## 输出格式
返回 JSON：
{{
  "summary": "导读摘要...",
  "tags": ["#标签1", "#标签2", "#标签3"]
}}
"""
